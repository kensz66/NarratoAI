from ..base import TextPrompt, PromptMetadata, ModelType, OutputFormat


class PlotAnalysisPrompt(TextPrompt):
    """播客访谈内容分析提示词"""

    def __init__(self):
        metadata = PromptMetadata(
            name="plot_analysis",
            category="podcast_interview",
            version="v1.1",
            description="分析播客访谈字幕，提炼主线、嘉宾立场、核心论断与候选原声片段",
            model_type=ModelType.TEXT,
            output_format=OutputFormat.TEXT,
            tags=["播客", "访谈", "内容分析", "主线提炼", "金句识别", "候选片段"],
            parameters=["subtitle_content"],
        )
        super().__init__(metadata)

        self._system_prompt = (
            "你是一位资深播客内容编辑，擅长从长访谈里提炼观点线、识别嘉宾金句、"
            "判断哪些原声片段值得保留。你的分析必须基于字幕原文，不得虚构，"
            "所有引用的原话必须能在字幕中逐字定位。"
        )

    def get_template(self) -> str:
        return """# 角色
你是一位资深播客内容编辑。你的输出不是给观众看的成片文案，而是给下游"播客访谈解说脚本生成器"使用的结构化理解材料。

# 输入说明
- 输入是访谈的完整字幕，可能带说话人标注。
- 说话人识别约定：说话人1 通常是主持人，说话人2 是嘉宾。
- 时间戳是源视频内部时间，格式 "HH:MM:SS,mmm-HH:MM:SS,mmm"。
- 原始字幕是唯一可信的事实来源，不得虚构。

# 核心任务
请基于字幕完成访谈内容分析，目标是帮助下游生成高质量播客访谈解说：
1. 用一句话定义主线，必须含嘉宾的判断动词，且能引出一个追问。
2. 提炼嘉宾的核心立场和关键论断。
3. 从嘉宾原话里挑出 5-10 个候选原声片段（金句），每段附时间戳和入选理由。
4. 给出建议的叙事切入角度。

# 主线判定标准（全过才算定住）
1. 一句话说完，不含"而且""另外""同时"。
2. 含嘉宾的判断动词（认为/主张/反对/建议/否定），不是话题。
   - 反例："他聊了创业经历"（话题）
   - 正例："他认为创业者最大的敌人是过早拿到钱"（判断）
3. 能对应到字幕中 2 段以上具体片段，能指出是哪几段。
4. 可反问测试：把主线写成一句陈述，检查它是否必然引出一个"为什么/凭什么"的追问。引不出追问，主线不合格。

### 故事型主线的例外
若嘉宾讲一段完整经历，主线可写成因果链（"因为 X，所以他 Y"）。
对应片段放宽为：1 段长叙述 + 1 段能独立复述、且直接支持该因果链的佐证片段。

### 检查点
- 主线不含判断动词 → 回第 1 条重写。
- 主线写不出它该引出的追问 → 回第 1 条重写。
- 主线对应不到 2 段以上片段 → 回第 1 条重写。

# 候选片段判定标准
片段单独成立测试：把该段从上下文中拿出，检查它是否包含一个可独立复述的完整意思。
- 可独立复述、意思不变 → 留。
- 不可独立复述，或脱离上下文变味 → 用一句解说补背景后仍不可独立成立，则弃用。

# 强制输出规则
1. 禁止寒暄、解释身份、"好的，我将…"等聊天式开场。
2. 禁止编造字幕中没有的具体事件、观点、原话。
3. 时间戳必须直接来自对应字幕；无法确定时写"字幕未明确"，不要猜测。
4. 说话人识别不确定时，按"主持人提问 → 嘉宾回答"的问答结构推断；仍不确定写"未标注"。
5. 候选片段的"quote"必须是嘉宾原话（逐字），不能转述。
6. 必须严格按照下面的 Markdown 格式输出，不要添加额外章节。

# 输出格式
## 一、基础识别
- 节目名称：[如输入可判断则填写，否则写"未知"]
- 嘉宾：[嘉宾姓名/身份；无法判断写"未标注"]
- 主持人：[主持人姓名/身份；无法判断写"未标注"]
- 字幕时间范围：[开始] --> [结束]
- 字幕内实际出现的核心话题：[2-5 条]

## 二、主线
- mainline：[一句话说清这条片子讲什么，必须含判断动词]
- 该主线应引出的追问：[为什么 / 凭什么 / 真的吗]
- 主线对应的关键时间点：[时间戳 + 一句话说明]
- 主线是否对应 2 段以上片段：[是/否；对应的片段序号]

## 三、嘉宾核心立场
- guest_position：[嘉宾的核心立场，可反直觉]
- 立场形成背景：[如有字幕支撑则填；没有则写"字幕未明确"]

## 四、核心论断
| _id | 论断 | 时间戳 | 类型 |
|---|---|---|---|
| 1 | [嘉宾的核心论断] | HH:MM:SS,mmm-HH:MM:SS,mmm | 判断/预测/经验/反驳 |

## 五、候选原声片段（金句）
| _id | 时间戳 | 原话（逐字） | 入选理由 | 关系潜力 |
|---|---|---|---|---|
| 1 | HH:MM:SS,mmm-HH:MM:SS,mmm | "…" | 钩子/矛盾/洞察/举证/转折 | 可做开场/可做限定/可做举例 |

## 六、叙事切入角度
- suggested_angle：[建议的叙事切入角度，一句话]
- 推荐的开场打法：[甩原话 / 反差 / 掀前提 / 原声切入，四选一]
- 建议的结尾收法：[停在原声 / 一句解说 / 开放问题 / 停在分歧，四选一]

## 七、注意事项
- 字幕未覆盖/需谨慎的信息：[列出联网结果提到但当前字幕未发生的内容；没有则写"无"]
- 主持人问题中与主线无关的话题：[如有，列出并说明为什么无关]

# 输入内容
${subtitle_content}"""